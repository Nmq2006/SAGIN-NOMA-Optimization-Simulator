function [opt_q, min_val] = solve_subproblem_position(current_a1, init_q, rho_val, params)
    obj_fun = @(q) calculate_outage_probability(current_a1, q, rho_val, params);
    opts = optimoptions('fmincon', ...
        'Display', 'off', ...
        'Algorithm', 'sqp', ...
        'StepTolerance', 1e-5, ...
        'OptimalityTolerance', 1e-5);
    [opt_q, min_val] = fmincon(obj_fun, init_q, [], [], [], [], ...
        params.uav_lb, params.uav_ub, [], opts);
end